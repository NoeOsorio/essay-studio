/**
 * Validation of what the model read from a document. Pure and browser-safe: the renderer uses it too.
 * The model proposes; code decides. A value is kept only when it appears in the text that was sent.
 * Malformed output is a failure, never partially applied.
 */

export type CitationAuthor = { apellidos: string; nombres?: string };
export type CitationFields = {
  titulo?: string;
  autores?: CitationAuthor[];
  anio?: string;
  revista?: string; volumen?: string; numero?: string; paginas?: string; editorial?: string; doi?: string;
};
/** `peso` is already mapped to 1 to 5. `id` is generated by the renderer, never by the model. */
export type ProposedCriterio = { nombre: string; descripcion: string; peso: number; cita: string };
export type ParseResult<T> = { ok: true; value: T } | { ok: false };

/** Canonical form for "appears": NFKC, case fold, all whitespace collapsed to one space. */
export function canonical(value: string): string {
  return value.normalize("NFKC").toLowerCase().replace(/\s+/g, " ").trim();
}

/** A one or two letter quote would "appear" in anything; it cannot back a criterion. */
const MIN_CITA_CHARS = 4;
const YEAR = /^(1[5-9]|20)\d\d$/;
const DEFAULT_WEIGHT = 3;

function readObject(raw: string): Record<string, unknown> | null {
  let text = raw.trim();
  const fence = /^```[a-zA-Z]*\s*([\s\S]*?)\s*```$/.exec(text);
  if (fence) text = fence[1].trim();
  try {
    const value: unknown = JSON.parse(text);
    return value && typeof value === "object" && !Array.isArray(value) ? value as Record<string, unknown> : null;
  } catch { return null; }
}

function text(value: unknown): string | undefined {
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (typeof value !== "string") return undefined;
  const trimmed = value.replace(/\s+/g, " ").trim();
  return trimmed || undefined;
}

export function parseCitation(raw: string, sentText: string): ParseResult<CitationFields> {
  const obj = readObject(raw);
  if (!obj) return { ok: false };
  const haystack = canonical(sentText);
  const appears = (value: string) => { const c = canonical(value); return c.length > 0 && haystack.includes(c); };
  const keep = (key: string): string | undefined => { const v = text(obj[key]); return v && appears(v) ? v : undefined; };

  const out: CitationFields = {};
  const titulo = keep("titulo"); if (titulo) out.titulo = titulo;
  for (const key of ["revista", "volumen", "numero", "paginas", "editorial", "doi"] as const) {
    const v = keep(key); if (v) out[key] = v;
  }
  const anio = text(obj.anio);
  if (anio && YEAR.test(anio) && appears(anio)) out.anio = anio;

  if (Array.isArray(obj.autores)) {
    const autores: CitationAuthor[] = [];
    for (const item of obj.autores) {
      if (!item || typeof item !== "object") continue;
      const a = item as Record<string, unknown>;
      const apellidos = text(a.apellidos);
      if (!apellidos || !appears(apellidos)) continue;
      const nombres = text(a.nombres);
      // Each name token must appear; an author that fails either part is dropped whole.
      if (nombres && !nombres.split(" ").every(appears)) continue;
      autores.push({ apellidos, ...(nombres ? { nombres } : {}) });
    }
    if (autores.length) out.autores = autores;
  }
  return { ok: true, value: out };
}

export type RubricProposal = { criterios: ProposedCriterio[]; sinCriterios: boolean };

export function parseRubric(raw: string, assignmentText: string): ParseResult<RubricProposal> {
  const obj = readObject(raw);
  if (!obj) return { ok: false };
  if (obj.sin_criterios === true && !Array.isArray(obj.criterios)) return { ok: true, value: { criterios: [], sinCriterios: true } };
  if (!Array.isArray(obj.criterios)) return { ok: false };

  const haystack = canonical(assignmentText);
  const appears = (value: string) => { const c = canonical(value); return c.length > 0 && haystack.includes(c); };
  const kept: { nombre: string; descripcion: string; cita: string; stated?: number }[] = [];
  for (const item of obj.criterios) {
    if (!item || typeof item !== "object") continue;
    const c = item as Record<string, unknown>;
    const nombre = text(c.nombre);
    const cita = text(c.cita);
    // The quote is what stops invented criteria.
    if (!nombre || !cita || canonical(cita).length < MIN_CITA_CHARS || !appears(cita)) continue;
    const declarado = text(c.peso_declarado);
    const valor = c.peso_valor;
    const stated = declarado && appears(declarado) && typeof valor === "number" && Number.isFinite(valor) && valor > 0 ? valor : undefined;
    kept.push({ nombre, descripcion: text(c.descripcion) ?? "", cita, ...(stated !== undefined ? { stated } : {}) });
  }
  if (kept.length === 0) return { ok: true, value: { criterios: [], sinCriterios: true } };

  // Stated values scale against the largest to 1 to 5, rounded, minimum 1. No stated weight gets 3.
  const largest = Math.max(0, ...kept.map((k) => k.stated ?? 0));
  const criterios = kept.map(({ stated, ...k }): ProposedCriterio => ({
    ...k, peso: stated === undefined ? DEFAULT_WEIGHT : Math.min(5, Math.max(1, Math.round((stated / largest) * 5))),
  }));
  return { ok: true, value: { criterios, sinCriterios: false } };
}
